import { chromium } from "playwright";
const b = await chromium.launch();
const p = await b.newPage();
const errors = [];
p.on("pageerror", (e) => errors.push("PAGEERROR: " + e.message.slice(0, 200)));
p.on("console", (m) => { if (m.type() === "error") errors.push("CONSOLE: " + m.text().slice(0, 200)); });
await p.setViewportSize({ width: 1440, height: 900 });
await p.goto("http://localhost:5199/sign-in", { waitUntil: "networkidle", timeout: 40000 });
await p.waitForTimeout(800);
const html = await p.content();
const hasAuthPanel = html.includes("auth-panel");
const hasAuthLayout = html.includes("auth-layout");
const hasRouterView = html.includes("auth-ubuntu-pattern");
const txt = (await p.evaluate(() => document.body.innerText)).slice(0, 150);
console.log("auth-layout:", hasAuthLayout, "| auth-panel:", hasAuthPanel, "| svg pattern:", hasRouterView);
console.log("body text:", JSON.stringify(txt));
console.log("errors:", JSON.stringify(errors, null, 2));
await p.screenshot({ path: ".claude/signin.png", fullPage: false });
await b.close();
